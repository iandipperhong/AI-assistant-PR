def normalize(name: str) -> str:
    """띄어쓰기·대소문자·다른 이름 차이를 무시하고 과목 이름을 비교하기 위한 키."""
    key = "".join(name.split()).lower()
    return ALIASES.get(key, key)


_BY_KEY: dict[str, Course] = {normalize(c.name): c for c in [*COURSES, *EXTRA_COURSES]}


def find_course(name: str) -> Course | None:
    return _BY_KEY.get(normalize(name))


def semester_label(name: str) -> str | None:
    c = find_course(name)
    if c is None:
        return None
    year, term = c.semester.split("-")
    return f"{year}학년 " + ("1·2학기" if term == "x" else f"{term}학기")
